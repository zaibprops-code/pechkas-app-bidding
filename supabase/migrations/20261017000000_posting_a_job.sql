-- --- Jobs ----------------------------------------------------------------------------------

CREATE SEQUENCE IF NOT EXISTS public.job_ref_seq START 1001;

CREATE TABLE IF NOT EXISTS public.jobs (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- What people say on the phone: "PK-1042". Never used in a link; it is
  -- guessable, and a job holds a home address.
  ref           text NOT NULL UNIQUE DEFAULT 'PK-' || nextval('public.job_ref_seq'),
  customer_id   uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  trade         text NOT NULL REFERENCES public.trades(slug),
  job_type_id   integer REFERENCES public.job_types(id),
  title         text NOT NULL,
  description   text CHECK (description IS NULL OR length(description) <= 500),
  offered_paisa bigint NOT NULL CHECK (offered_paisa > 0 AND offered_paisa % 100 = 0),
  when_kind     text NOT NULL CHECK (when_kind IN ('now', 'today', 'tomorrow')),
  when_part     text CHECK (when_part IN ('morning', 'afternoon', 'evening')),
  sector        text NOT NULL REFERENCES public.sectors(name),
  street        text NOT NULL CHECK (length(btrim(street)) BETWEEN 1 AND 60),
  house         text NOT NULL CHECK (length(btrim(house)) BETWEEN 1 AND 60),
  landmark      text CHECK (landmark IS NULL OR length(landmark) <= 120),
  lat           double precision CHECK (lat IS NULL OR lat BETWEEN 23 AND 37.5),
  lng           double precision CHECK (lng IS NULL OR lng BETWEEN 60 AND 78),
  power         text CHECK (power IN ('on', 'off')),
  parts         text CHECK (parts IN ('pro_buys', 'customer_has')),
  gate_note     text CHECK (gate_note IS NULL OR length(gate_note) <= 120),
  status        text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'cancelled')),
  cancelled_by  text CHECK (cancelled_by IN ('customer', 'office')),
  cancel_reason text CHECK (cancel_reason IS NULL OR length(cancel_reason) <= 200),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CHECK ((lat IS NULL) = (lng IS NULL)),
  CHECK ((when_kind = 'now') = (when_part IS NULL))
);
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS jobs_customer ON public.jobs (customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS jobs_status ON public.jobs (status, created_at DESC);

/**
 * The voice note, video and photos that show what is wrong. The files are in
 * the private `job-media` bucket under the customer's own folder; this table
 * says which belong to which job.
 */
CREATE TABLE IF NOT EXISTS public.job_media (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  job_id     uuid NOT NULL REFERENCES public.jobs(id) ON DELETE CASCADE,
  kind       text NOT NULL CHECK (kind IN ('voice', 'video', 'photo')),
  path       text NOT NULL UNIQUE,
  seconds    smallint CHECK (seconds IS NULL OR seconds BETWEEN 0 AND 600),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.job_media ENABLE ROW LEVEL SECURITY;
CREATE INDEX IF NOT EXISTS job_media_job ON public.job_media (job_id);


-- --- The private bucket ---------------------------------------------------------------------
--
-- Files go in `<their own id>/<anything>`. A person may put files only in
-- their own folder and read only their own folder; the office reads all of
-- it. Nobody else, and never the public key: there is no policy for anon.
-- Phase 3 adds the one technician a customer chooses, through a function.

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'job-media', 'job-media', false, 31457280,  -- 30 MB, a short phone video
  ARRAY['audio/mp4', 'audio/m4a', 'audio/x-m4a', 'audio/aac', 'audio/mpeg',
        'video/mp4', 'video/quicktime', 'video/3gpp',
        'image/jpeg', 'image/png', 'image/webp']
)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "job media: upload to own folder" ON storage.objects;
CREATE POLICY "job media: upload to own folder" ON storage.objects
  FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'job-media' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS "job media: read own folder, or the office" ON storage.objects;
CREATE POLICY "job media: read own folder, or the office" ON storage.objects
  FOR SELECT TO authenticated
  USING (bucket_id = 'job-media' AND ((storage.foldername(name))[1] = auth.uid()::text OR public.is_staff()));

-- So a customer deleting their account can take their recordings with them.
DROP POLICY IF EXISTS "job media: delete own folder" ON storage.objects;
CREATE POLICY "job media: delete own folder" ON storage.objects
  FOR DELETE TO authenticated
  USING (bucket_id = 'job-media' AND (storage.foldername(name))[1] = auth.uid()::text);


