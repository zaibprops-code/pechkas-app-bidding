/**
 * Every line of Roman Urdu a technician can read, beside its English, in one
 * file the owner can read on his phone: docs/ROMAN_URDU.md.
 *
 *   npm run words          rewrites the file
 *   npm run words:check    fails if the file is out of date (part of `npm run check`)
 *
 * The screens' words come from apps/mobile/src/words.ts. The notifications'
 * words come from the database itself: every migration is applied to a
 * throwaway Postgres in memory and `push_words` is read back, so the list is
 * what Supabase will actually send, after every later change.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const ROOT = process.cwd();
const OUT = join(ROOT, 'docs', 'ROMAN_URDU.md');

// --- The screens -------------------------------------------------------------
const source = await readFile(join(ROOT, 'apps', 'mobile', 'src', 'words.ts'), 'utf8');
const start = source.indexOf('const PRO = ');
const end = source.indexOf('} as const;', start);
if (start < 0 || end < 0) throw new Error('Could not find `const PRO = { … } as const;` in words.ts');
// A plain object literal of strings, from our own file.
const PRO = new Function(`return ${source.slice(start + 'const PRO = '.length, end + 1)}`)();

// --- The notifications -------------------------------------------------------
const { db, migrate } = await import(join(ROOT, 'supabase', 'tests', 'harness.mjs'));
await migrate();
const { rows: pushes } = await db.query(`SELECT key, ur, en, who FROM public.push_words ORDER BY sort`);

const cell = (t) => String(t ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (rows) => ['| | Roman Urdu | English |', '| --- | --- | --- |', ...rows.map(([k, ur, en]) => `| \`${k}\` | ${cell(ur)} | ${cell(en)} |`)].join('\n');

const screens = Object.keys(PRO.ur).map((k) => [k, PRO.ur[k], PRO.en[k]]);
const technician = pushes.filter((r) => r.who === 'technician' || r.who === 'both').map((r) => [r.key, r.ur, r.en]);
const englishOnly = pushes.filter((r) => r.who === 'customer' || r.who === 'office');

const text = `# Every Roman Urdu line

Written by \`npm run words\` — do not edit this file. To change a line, tell
Claude which one (the name in the first column) and what it should say.

Please read every line as a technician would, on a phone. Is it how a
technician in Islamabad talks? Is anything rude, too formal, or unclear?
\`{name}\` is filled in when it is shown, e.g. \`{price}\` becomes Rs 5,500.

## Notifications a technician receives

Sent by the database, so these live in \`push_words\`
(\`supabase/migrations/\`). They show on his lock screen.

${table(technician)}

## The technician's screens

From \`apps/mobile/src/words.ts\`.

${table(screens)}

## English only

Customers and the office read English, so these have no Roman Urdu:
${englishOnly.map((r) => `\`${r.key}\``).join(', ')}.
`;

if (process.argv.includes('--check')) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current !== text) {
    console.log('\n✗ docs/ROMAN_URDU.md is out of date. Run `npm run words` and commit it.\n');
    process.exit(1);
  }
  console.log('docs/ROMAN_URDU.md is up to date.');
} else {
  await writeFile(OUT, text);
  console.log(`Wrote docs/ROMAN_URDU.md: ${technician.length} notification lines, ${screens.length} screen lines.`);
}
